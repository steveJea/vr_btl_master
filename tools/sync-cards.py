#!/usr/bin/env python3
"""Refresh the teaser roster from the main game.

Source: https://github.com/steveJea/vr-tcg/blob/main/data/cards.csv
The source table has a personal field that this site must not publish.
That column is checked, then dropped before writing js/cards-data.js
and worker/cards.json.
"""

import csv
import io
import json
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = 'https://raw.githubusercontent.com/steveJea/vr-tcg/main/data/cards.csv'
PREVIOUS = 'https://raw.githubusercontent.com/steveJea/vr-ideal-worldcup/main/VR_DATA.csv'


def fetch(url):
    with urllib.request.urlopen(url, timeout=60) as response:
        return response.read().decode('utf-8-sig')


def rows(text):
    return list(csv.DictReader(io.StringIO(text)))


def main():
    current = rows(fetch(SOURCE))
    previous = {row['id']: row for row in rows(fetch(PREVIOUS))}
    assert current and all(row.get('age', '').strip() for row in current)

    name_changes = []
    power_changes = []
    cards = []
    for row in current:
        old = previous.get(row['id'])
        if old and old['name'] != row['name']:
            name_changes.append({'id': row['id'], 'from': old['name'], 'to': row['name'], 'grade': row['grade'], 'gender': row['gender']})
        if old and int(float(old['power'])) != int(float(row['power'])):
            power_changes.append({'id': row['id'], 'name': row['name'], 'from': int(float(old['power'])), 'to': int(float(row['power']))})
        cards.append({
            'id': row['id'],
            'name': row['name'],
            'gender': row['gender'],
            'region': row['region'],
            'grade': row['grade'],
            'class': row['class'],
            'attribute': row['attribute'],
            'power': int(float(row['power'])),
            'hp': int(float(row['HP'] or 0)),
            'atk': int(float(row['ATK'] or 0)),
            'def': int(float(row['DEF'] or 0)),
            'phy': int(float(row['PHY'] or 0)),
            'men': int(float(row['MEN'] or 0)),
            'mor': int(float(row['MOR'] or 0)),
        })

    assert all('age' not in card and card['id'] != '10533' for card in cards)
    header = '\n'.join([
        '// Generated by tools/sync-cards.py from steveJea/vr-tcg data/cards.csv.',
        '// Personal character fields from the source table are not copied into this module.',
        '// Name updates versus the world-cup CSV this site used to fetch:',
        *[f"//   {item['id']} {item['from']} -> {item['to']}" for item in name_changes],
        f"// POWER changes versus that CSV: {len(power_changes)}.",
        'export const CARD_DATA = ' + json.dumps(cards, ensure_ascii=False, separators=(',', ':')) + ';',
        '',
    ])
    (ROOT / 'js' / 'cards-data.js').write_text(header, encoding='utf-8')
    worker_cards = {card['id']: {'name': card['name'], 'gender': card['gender'], 'power': card['power']} for card in cards}
    (ROOT / 'worker' / 'cards.json').write_text(json.dumps(worker_cards, ensure_ascii=False, separators=(',', ':')), encoding='utf-8')
    report = {
        'source': SOURCE,
        'cardCount': len(cards),
        'excludedId10533': True,
        'personalFieldPublished': False,
        'nameChanges': name_changes,
        'powerChanges': power_changes,
    }
    (ROOT / 'tools' / 'sync-report.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(json.dumps({'cards': len(cards), 'nameChanges': len(name_changes), 'powerChanges': len(power_changes)}, ensure_ascii=False))


if __name__ == '__main__':
    main()
